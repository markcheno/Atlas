#!/usr/bin/env node
// Generates docs/dependency-licenses.md from `cargo metadata` and
// `pnpm licenses list`. Run with `pnpm license-report`; commit the result.
//
// With --spikes it instead writes docs/spike-dependency-licenses.md for the
// Slice 0.9 spike workspaces (spikes/), which are not part of the app.
//
// Cargo metadata is not filtered by platform, so crates used only on
// Windows or Linux are included. A dependency is flagged when it cannot be
// used under a permissive license: every OR-alternative contains a copyleft
// or unknown term. "A OR B" where one side is permissive is not flagged.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pdfiumPin = JSON.parse(readFileSync(join(root, 'tools.lock.json'), 'utf8')).tools.pdfium;
const run = (cmd, args) =>
  execFileSync(cmd, args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

const COPYLEFT = /\b(A?GPL|LGPL|MPL|EPL|CDDL|EUPL|OSL|SSPL|CC-BY-SA)/i;

/** Returns null when a permissive reading exists, else a reason. */
function flag(license) {
  if (!license || license === 'UNKNOWN') return 'no license metadata';
  const normalized = license.replace(/\s*\/\s*/g, ' OR ').replace(/[()]/g, '');
  const alternatives = normalized.split(/\s+OR\s+/i);
  const permissive = alternatives.some((alt) => !COPYLEFT.test(alt));
  return permissive ? null : 'copyleft in every alternative';
}

if (process.argv.includes('--spikes')) {
  spikeReport();
  process.exit(0);
}

// ---- Rust crates
const meta = JSON.parse(
  run('cargo', [
    'metadata',
    '--format-version',
    '1',
    '--locked',
    '--manifest-path',
    'src-tauri/Cargo.toml',
  ]),
);
const workspace = new Set(meta.workspace_members);
const crates = meta.packages
  .filter((p) => !workspace.has(p.id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? 'UNKNOWN' }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// ---- npm packages
function npm(prodOnly) {
  const args = ['licenses', 'list', '--json'];
  if (prodOnly) args.push('--prod');
  const grouped = JSON.parse(run('pnpm', args));
  return Object.entries(grouped)
    .flatMap(([license, pkgs]) =>
      pkgs.map((p) => ({ name: p.name, version: p.versions.join(', '), license })),
    )
    .sort((a, b) => a.name.localeCompare(b.name));
}
const npmProd = npm(true);
const prodNames = new Set(npmProd.map((p) => p.name));
const npmDev = npm(false).filter((p) => !prodNames.has(p.name));

// ---- render
function counts(rows) {
  const c = new Map();
  for (const r of rows) c.set(r.license, (c.get(r.license) ?? 0) + 1);
  return [...c.entries()].sort((a, b) => b[1] - a[1]);
}
function table(rows) {
  return ['| Package | Version | License |', '| --- | --- | --- |']
    .concat(rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`))
    .join('\n');
}
function summary(rows) {
  return ['| License expression | Count |', '| --- | --- |']
    .concat(counts(rows).map(([l, n]) => `| ${l} | ${n} |`))
    .join('\n');
}
const flagged = [
  ...crates.map((r) => ({ ...r, scope: 'Rust crate (runtime, build-time, or other-platform)' })),
  ...npmProd.map((r) => ({ ...r, scope: 'npm (shipped in UI bundle)' })),
  ...npmDev.map((r) => ({ ...r, scope: 'npm (build/test tool only)' })),
]
  .map((r) => ({ ...r, reason: flag(r.license) }))
  .filter((r) => r.reason);

const md = `# Dependency licenses

Generated by \`pnpm license-report\` (scripts/license-report.mjs). Do not edit by hand.

Atlas's own license is an open decision (product spec, section 16). This
inventory exists so that decision, and any future copyleft dependency, is
made with the obligations visible.

## Needs review

Dependencies with no permissive alternative. MPL-2.0 is file-level weak
copyleft: shipping unmodified binaries is compatible with a permissive or
commercial Atlas, but modified MPL files must be published. Build and test
tools are not redistributed.

${
  flagged.length
    ? ['| Package | Version | License | Scope | Reason |', '| --- | --- | --- | --- | --- |']
        .concat(
          flagged.map(
            (r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.scope} | ${r.reason} |`,
          ),
        )
        .join('\n')
    : 'None.'
}

## Native libraries shipped with the app

Not described by Cargo or npm metadata; kept by hand in scripts/license-report.mjs.
Their notices ship in every bundle under \`licenses/\`.

| Component | Where | License |
| --- | --- | --- |
${appNativeComponents()
  .map(([a, b, c]) => `| ${a} | ${b} | ${c} |`)
  .join('\n')}

Not covered: system libraries the OS provides at runtime (WebKit on macOS,
WebView2 on Windows, WebKitGTK and GTK on Linux). They are not bundled,
except that the Linux AppImage carries WebKitGTK and GTK (docs/packaging.md).
The other libraries and models the Slice 0.9 spike measured (Docling and its
models, vector engines) are in
[spike-dependency-licenses.md](spike-dependency-licenses.md); one joins
this report only when the app adopts it (ADR 0008).

## Summary

### Rust crates (${crates.length}, all platforms)

${summary(crates)}

### npm runtime packages (${npmProd.length}, shipped in the UI bundle)

${summary(npmProd)}

### npm development packages (${npmDev.length}, not shipped)

${summary(npmDev)}

## Full inventory

### Rust crates

${table(crates)}

### npm runtime packages

${table(npmProd)}

### npm development packages

${table(npmDev)}
`;

writeFileSync(join(root, 'docs', 'dependency-licenses.md'), md);
console.log(
  `Wrote docs/dependency-licenses.md: ${crates.length} crates, ${npmProd.length} runtime npm, ${npmDev.length} dev npm, ${flagged.length} flagged.`,
);

