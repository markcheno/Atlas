"""Generates the synthetic part of the spike corpus (docs/spike-0.9.md).

    uv run make.py             # needs `just spike-tools` (typst) and fetch.py's output

Born-digital PDFs are typeset with typst from public-domain text (Project
Gutenberg's Alice and Candide), so the exact text is known; that text is
written to corpus/truth/. Also generated: a PDF whose fonts lack ToUnicode
maps, image-only ("scanned") PDFs, and malformed PDFs and EPUBs.
Everything lands in corpus/ and is recorded in corpus/manifest.json.
"""

import io
import json
import random
import re
import shutil
import subprocess
import tempfile
import zipfile
from pathlib import Path

from PIL import Image, ImageFilter
from pypdf import PdfReader, PdfWriter
from pypdf.generic import NameObject

from fetch import CORPUS, HERE, document, load_manifest, put, save_manifest

TOOLS = json.loads((HERE.parent.parent / ".tools" / "paths.json").read_text())
TYPST = TOOLS["typst"]["bin"]
GENERATED = "Generated for Atlas from public-domain text (Project Gutenberg); no rights reserved"
SEED = 9


def gutenberg_paragraphs(name: str) -> list[str]:
    text = (CORPUS / "text" / name).read_text(encoding="utf-8")
    start = text.index("*** START OF")
    start = text.index("\n", start) + 1
    end = text.index("*** END OF")
    body = text[start:end].replace("\r\n", "\n")
    paras = [re.sub(r"\s+", " ", p.replace("_", "")).strip() for p in re.split(r"\n\s*\n", body)]
    return [p for p in paras if p]


def chapters(paras: list[str]) -> list[list[str]]:
    out: list[list[str]] = []
    for p in paras:
        if re.match(r"^CHAPTER [IVXL]+\.", p):
            out.append([p])
        elif out:
            out[-1].append(p)
    return out


def typ_string(s: str) -> str:
    return '#"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def typeset(name: str, preamble: str, paras: list[str], extra: str = "") -> bytes:
    body = "\n\n".join(typ_string(p) for p in paras)
    src = f'#set document(title: "{name}", date: datetime(year: 2026, month: 11, day: 8))\n{preamble}\n{body}\n{extra}\n'
    with tempfile.TemporaryDirectory() as d:
        (Path(d) / "doc.typ").write_text(src, encoding="utf-8")
        subprocess.run([TYPST, "compile", "doc.typ", "doc.pdf"], cwd=d, check=True)
        return (Path(d) / "doc.pdf").read_bytes()


def typeset_png(paras: list[str], ppi: int = 150) -> list[Image.Image]:
    body = "\n\n".join(typ_string(p) for p in paras)
    src = f'#set page(width: 14cm, height: 21cm, margin: 1.6cm)\n#set text(size: 11pt)\n{body}\n'
    with tempfile.TemporaryDirectory() as d:
        (Path(d) / "doc.typ").write_text(src, encoding="utf-8")
        subprocess.run([TYPST, "compile", "--format", "png", "--ppi", str(ppi), "doc.typ", "page-{0p}.png"], cwd=d, check=True)
        return [Image.open(p).convert("L").copy() for p in sorted(Path(d).glob("page-*.png"))]


def images_to_pdf(images: list[Image.Image], resolution: float) -> bytes:
    buf = io.BytesIO()
    first, *rest = [im.convert("RGB") for im in images]
    first.save(buf, "PDF", save_all=True, append_images=rest, resolution=resolution)
    return buf.getvalue()


def degrade(im: Image.Image, rng: random.Random) -> Image.Image:
    """Makes a clean render look scanned: slight rotation, blur, noise."""
    im = im.rotate(rng.uniform(-0.8, 0.8), resample=Image.Resampling.BICUBIC, fillcolor=255)
    im = im.filter(ImageFilter.GaussianBlur(0.6))
    px = im.load()
    w, h = im.size
    for _ in range(w * h // 60):
        x, y = rng.randrange(w), rng.randrange(h)
        px[x, y] = max(0, min(255, px[x, y] + rng.randint(-60, 60)))
    return im


def truth(m: dict, name: str, paras: list[str], note: str) -> str:
    rel = f"truth/{name}.txt"
    put(m, rel, ("\n\n".join(paras) + "\n").encode(), "generated by generator/make.py", GENERATED, note)
    return rel


def strip_tounicode(pdf: bytes) -> bytes:
    reader = PdfReader(io.BytesIO(pdf))
    writer = PdfWriter(clone_from=reader)
    for page in writer.pages:
        fonts = page["/Resources"].get_object().get("/Font", {})
        for ref in fonts.get_object().values():
            font = ref.get_object()
            if NameObject("/ToUnicode") in font:
                del font[NameObject("/ToUnicode")]
            for desc in font.get("/DescendantFonts", []):
                d = desc.get_object()
                if NameObject("/ToUnicode") in d:
                    del d[NameObject("/ToUnicode")]
    out = io.BytesIO()
    writer.write(out)
    return out.getvalue()


def minimal_pdf(content_objects: list[bytes]) -> bytes:
    """A hand-assembled PDF with a correct xref table."""
    objs = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R >>",
        *content_objects,
    ]
    out = io.BytesIO()
    out.write(b"%PDF-1.7\n")
    offsets = []
    for i, body in enumerate(objs, start=1):
        offsets.append(out.tell())
        out.write(f"{i} 0 obj\n".encode() + body + b"\nendobj\n")
    xref = out.tell()
    out.write(f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode())
    for off in offsets:
        out.write(f"{off:010} 00000 n \n".encode())
    out.write(f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
    return out.getvalue()


def epub_zip(entries: list[tuple[str, bytes]], compress: bool = True) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr(zipfile.ZipInfo("mimetype"), b"application/epub+zip", compress_type=zipfile.ZIP_STORED)
        for name, data in entries:
            info = zipfile.ZipInfo(name)
            info.compress_type = zipfile.ZIP_DEFLATED if compress else zipfile.ZIP_STORED
            z.writestr(info, data)
    return buf.getvalue()


CONTAINER = b"""<?xml version="1.0"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles><rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/></rootfiles>
</container>"""


def opf(items: list[tuple[str, str]]) -> bytes:
    manifest = "\n".join(f'<item id="{i}" href="{h}" media-type="application/xhtml+xml"/>' for i, h in items)
    spine = "\n".join(f'<itemref idref="{i}"/>' for i, _ in items)
    return f"""<?xml version="1.0"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="id">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="id">urn:atlas:spike</dc:identifier><dc:title>Atlas malformed test</dc:title><dc:language>en</dc:language>
    <meta property="dcterms:modified">2026-11-08T00:00:00Z</meta>
  </metadata>
  <manifest>{manifest}</manifest>
  <spine>{spine}</spine>
</package>""".encode()


def xhtml(body: str) -> bytes:
    return f'<?xml version="1.0"?><html xmlns="http://www.w3.org/1999/xhtml"><head><title>t</title></head><body>{body}</body></html>'.encode()


def make_generated(m: dict) -> None:
    alice = chapters(gutenberg_paragraphs("pg11.txt"))
    candide = gutenberg_paragraphs("pg4650.txt")

    # One column, running header and page numbers (not part of the truth).
    paras = alice[0] + alice[1]
    pdf = typeset("One column", '#set page(header: align(right)[Alice test document], numbering: "1")\n#set par(justify: true)', paras)
    put(m, "pdf/generated/one-column.pdf", pdf, "generated by generator/make.py", GENERATED, "Alice ch. I–II, one column, header and page numbers")
    t = truth(m, "one-column", paras, "exact text of pdf/generated/one-column.pdf, without header and page numbers")
    document(m, {"id": "gen-one-column", "path": "pdf/generated/one-column.pdf", "kind": "pdf-generated", "expect": "text",
                 "layout": "one-column", "truth": {"path": t, "kind": "exact"}})

    # The same document, fonts without ToUnicode maps.
    put(m, "pdf/generated/no-tounicode.pdf", strip_tounicode(pdf), "generated by generator/make.py", GENERATED,
        "one-column.pdf with every /ToUnicode map removed")
    document(m, {"id": "gen-no-tounicode", "path": "pdf/generated/no-tounicode.pdf", "kind": "pdf-generated", "expect": "needs-ocr",
                 "layout": "one-column", "truth": {"path": t, "kind": "exact"},
                 "note": "The text layer can't be mapped back to Unicode; the right result is to notice (empty or garbled text) and send it to OCR"})

    # Two columns.
    paras = alice[2] + alice[3]
    pdf = typeset("Two columns", '#set page(columns: 2, numbering: "1")\n#set par(justify: true)\n#set text(size: 10pt)', paras)
    put(m, "pdf/generated/two-column.pdf", pdf, "generated by generator/make.py", GENERATED, "Alice ch. III–IV, two columns")
    t = truth(m, "two-column", paras, "exact text of pdf/generated/two-column.pdf, without page numbers")
    document(m, {"id": "gen-two-column", "path": "pdf/generated/two-column.pdf", "kind": "pdf-generated", "expect": "text",
                 "layout": "two-column", "truth": {"path": t, "kind": "exact"}})

    # Ligatures, accents, a table and footnotes.
    lig = ("The official office staff were efficient and affluent; they shuffled the fluffy waffles, "
           "flipped the flat files, and found the final figures difficult to fit in the first fifty fields.")
    french = candide[10:16]
    rows = [("Item", "Quantity", "Price"), ("Café crème", "2", "3,50 €"), ("Thé à la menthe", "1", "2,80 €"), ("Crêpe flambée", "3", "12,00 €")]
    table = "#table(columns: 3, " + ", ".join(f"[{typ_string(c)}]" for r in rows for c in r) + ")"
    notes = ["First footnote: an official affidavit.", "Second footnote: naïve façade, déjà vu."]
    body = [lig, *french]
    extra = f"\n{table}\n\nSee the notes.#footnote[{typ_string(notes[0])}] And again.#footnote[{typ_string(notes[1])}]\n"
    pdf = typeset("Features", '#set page(numbering: "1")\n#set text(lang: "fr")', body, extra)
    put(m, "pdf/generated/features.pdf", pdf, "generated by generator/make.py", GENERATED,
        "ligatures, French (Candide), a table and two footnotes")
    truth_paras = [*body, " ".join(c for r in rows for c in r), "See the notes. And again.", *notes]
    t = truth(m, "features", truth_paras, "exact text of pdf/generated/features.pdf; table row-major, footnotes last")
    document(m, {"id": "gen-features", "path": "pdf/generated/features.pdf", "kind": "pdf-generated", "expect": "text",
                 "layout": "one-column", "truth": {"path": t, "kind": "exact"}, "note": "ligatures, accents, table, footnotes"})

    # A whole book, for throughput.
    paras = [p for ch in alice for p in ch]
    pdf = typeset("Book", '#set page(numbering: "1")\n#set par(justify: true)', paras)
    put(m, "pdf/generated/book.pdf", pdf, "generated by generator/make.py", GENERATED, "all of Alice, one column")
    t = truth(m, "book", paras, "exact text of pdf/generated/book.pdf, without page numbers")
    document(m, {"id": "gen-book", "path": "pdf/generated/book.pdf", "kind": "pdf-generated", "expect": "text",
                 "layout": "one-column", "truth": {"path": t, "kind": "exact"}, "note": "throughput"})

    # Owner-password only: opens without a password, so text is expected.
    w = PdfWriter(clone_from=PdfReader(io.BytesIO(put_bytes(m, "pdf/generated/one-column.pdf"))))
    w.encrypt(user_password="", owner_password="owner", algorithm="RC4-128")
    out = io.BytesIO()
    w.write(out)
    put(m, "pdf/generated/owner-password.pdf", out.getvalue(), "generated by generator/make.py", GENERATED,
        "one-column.pdf, RC4-128, owner password only (opens without one)")
    document(m, {"id": "gen-owner-password", "path": "pdf/generated/owner-password.pdf", "kind": "pdf-generated", "expect": "text",
                 "layout": "one-column", "truth": {"path": "truth/one-column.txt", "kind": "exact"}})


def put_bytes(m: dict, rel: str) -> bytes:
    return (CORPUS / rel).read_bytes()


def make_scanned(m: dict) -> None:
    rng = random.Random(SEED)
    alice = chapters(gutenberg_paragraphs("pg11.txt"))
    paras = alice[4][:10]
    images = [degrade(im, rng) for im in typeset_png(paras)]
    put(m, "pdf/scanned/synthetic-scan.pdf", images_to_pdf(images, 150.0), "generated by generator/make.py", GENERATED,
        "Alice ch. V rendered at 150 ppi, rotated, blurred and speckled; image only")
    t = truth(m, "synthetic-scan", paras, "text shown in pdf/scanned/synthetic-scan.pdf (for OCR later)")
    document(m, {"id": "scan-synthetic", "path": "pdf/scanned/synthetic-scan.pdf", "kind": "pdf-scanned", "expect": "needs-ocr",
                 "truth": {"path": t, "kind": "exact"}})

    pages = sorted((HERE / "build" / "scan").glob("n*.jpg"))
    if pages:
        src = m["sources"]["ia-scan"]
        put(m, "pdf/scanned/ia-alice-1894.pdf", images_to_pdf([Image.open(p) for p in pages], 130.0), src["item"], src["license"],
            src["note"] + "; 4 page images combined into an image-only PDF")
        document(m, {"id": "scan-ia-alice-1894", "path": "pdf/scanned/ia-alice-1894.pdf", "kind": "pdf-scanned", "expect": "needs-ocr",
                     "note": "real scan, 1894 edition"})


def make_malformed(m: dict) -> None:
    good = put_bytes(m, "pdf/generated/one-column.pdf")
    note = "generated by generator/make.py"

    def bad(name: str, data: bytes, desc: str, expect: str = "no-crash") -> None:
        put(m, f"malformed/{name}", data, note, GENERATED, desc)
        kind = "epub" if name.endswith(".epub") else "pdf"
        document(m, {"id": f"bad-{name.rsplit('.', 1)[0]}", "path": f"malformed/{name}", "kind": f"malformed-{kind}", "expect": expect, "note": desc})

    bad("zero-bytes.pdf", b"", "empty file")
    bad("not-a-pdf.pdf", b"This is a plain text file with a .pdf name.\n" * 20, "plain text named .pdf")
    bad("truncated.pdf", good[: len(good) // 2], "first half of one-column.pdf")
    broken = re.sub(rb"startxref\s+\d+", b"startxref\n999999999", good)
    broken = re.sub(rb"xref\s", b"xrxx ", broken, count=1)
    bad("broken-xref.pdf", broken, "one-column.pdf with a corrupted xref keyword and a bogus startxref")
    w = PdfWriter(clone_from=PdfReader(io.BytesIO(good)))
    w.encrypt(user_password="secret", owner_password="owner", algorithm="RC4-128")
    out = io.BytesIO()
    w.write(out)
    bad("user-password.pdf", out.getvalue(), "one-column.pdf, RC4-128, needs a user password", expect="encrypted")
    nested = b"<< /Length 0 >>\nstream\n\nendstream"
    deep = b"[" * 200_000 + b"]" * 200_000
    bad("deep-nesting.pdf", minimal_pdf([nested, b"<< /Deep " + deep + b" >>"]), "an object nested 200,000 arrays deep")
    huge_stream = b"BT /F1 12 Tf 72 720 Td (" + b"A" * 50 + b") Tj ET\n"
    bad("bad-length.pdf", minimal_pdf([b"<< /Length 99999999 >>\nstream\n" + huge_stream + b"endstream"]),
        "content stream whose /Length is far larger than the data")

    chapter = xhtml("<h1>One</h1><p>Some text.</p>")
    bad("no-opf.epub", epub_zip([("META-INF/container.xml", CONTAINER), ("OEBPS/c1.xhtml", chapter)]),
        "container.xml points to an OPF that isn't in the archive")
    bad("not-an-epub.epub", bytes(random.Random(SEED).randrange(256) for _ in range(4096)), "4 KiB of random bytes")
    bad("zip-slip.epub", epub_zip([("META-INF/container.xml", CONTAINER), ("OEBPS/content.opf", opf([("c1", "../../escape.xhtml")])),
                                   ("../../escape.xhtml", chapter)]), "a spine item stored at ../../escape.xhtml")
    bomb = xhtml("<p>" + "bomb " * (64 * 1024 * 1024 // 5) + "</p>")
    bad("zip-bomb.epub", epub_zip([("META-INF/container.xml", CONTAINER), ("OEBPS/content.opf", opf([("c1", "c1.xhtml")])),
                                   ("OEBPS/c1.xhtml", bomb)]), "one 64 MiB chapter that compresses to well under 1 MiB")
    enc = b"""<?xml version="1.0"?>
<encryption xmlns="urn:oasis:names:tc:opendocument:xmlns:container" xmlns:enc="http://www.w3.org/2001/04/xmlenc#">
  <enc:EncryptedData><enc:EncryptionMethod Algorithm="http://www.w3.org/2001/04/xmlenc#aes128-cbc"/>
    <enc:CipherData><enc:CipherReference URI="OEBPS/c1.xhtml"/></enc:CipherData></enc:EncryptedData>
</encryption>"""
    bad("drm.epub", epub_zip([("META-INF/container.xml", CONTAINER), ("META-INF/encryption.xml", enc),
                              ("OEBPS/content.opf", opf([("c1", "c1.xhtml")])),
                              ("OEBPS/c1.xhtml", bytes(random.Random(SEED + 1).randrange(256) for _ in range(2048)))]),
        "content listed in META-INF/encryption.xml (DRM); the chapter is random bytes", expect="encrypted")


if __name__ == "__main__":
    manifest = load_manifest()
    make_generated(manifest)
    make_scanned(manifest)
    make_malformed(manifest)
    save_manifest(manifest)
    total = sum(f["bytes"] for f in manifest["files"].values())
    print(f"manifest: {len(manifest['files'])} files ({total / 1048576:.1f} MiB), {len(manifest['documents'])} documents")
    shutil.rmtree(HERE / "build" / "tmp", ignore_errors=True)
